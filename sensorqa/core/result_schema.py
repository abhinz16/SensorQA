#!/usr/bin/env python3
# -*- coding: utf-8 -*-

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any


class ExecutionStatus(str, Enum):
    """
    Describes whether an analysis tool executed successfully.
    """

    SUCCESS = "success"
    SKIPPED = "skipped"
    ERROR = "error"


class QualificationStatus(str, Enum):
    """
    Describes whether a calculated metric satisfies an engineering requirement.
    """

    PASS = "pass"
    FAIL = "fail"
    NOT_EVALUATED = "not_evaluated"


class EvidenceStrength(str, Enum):
    """
    Strength of evidence supporting a diagnostic observation or hypothesis.
    """

    WEAK = "weak"
    MODERATE = "moderate"
    STRONG = "strong"


@dataclass
class MetricResult:
    """
    A single numerical result produced by an analysis tool.

    Example:
        name = "Gyroscope X-axis Bias"
        value = 0.018
        unit = "deg/s"
    """

    name: str
    value: float | int | None
    unit: str | None = None
    description: str | None = None


@dataclass
class Evidence:
    """
    Evidence produced by an analysis that may later be used
    by the SensorQA diagnostic engine.

    Example:
        statement = "Measurement offset increases with temperature."
        strength = EvidenceStrength.STRONG
    """

    statement: str
    strength: EvidenceStrength
    supporting_metrics: list[str] = field(default_factory=list)


@dataclass
class PlotResult:
    """
    Describes a plot generated by an analysis tool.

    The actual plotting implementation will be added later.
    """

    plot_id: str
    title: str
    plot_type: str
    description: str | None = None
    file_path: str | None = None


@dataclass
class AnalysisResult:
    """
    Standard result returned by every SensorQA analysis tool.

    All built-in and custom analysis tools must return
    an AnalysisResult object.
    """

    tool_id: str
    tool_name: str
    tool_version: str

    status: ExecutionStatus

    metrics: list[MetricResult] = field(default_factory=list)
    evidence: list[Evidence] = field(default_factory=list)
    plots: list[PlotResult] = field(default_factory=list)

    warnings: list[str] = field(default_factory=list)
    messages: list[str] = field(default_factory=list)

    metadata: dict[str, Any] = field(default_factory=dict)

    def add_metric(
        self,
        name: str,
        value: float | int | None,
        unit: str | None = None,
        description: str | None = None,
    ) -> None:
        """Convenience method for adding a metric to the result.
        
        Args:
            name: Name of the item.
            value: Value to process.
            unit: Engineering unit.
            description: Value for `description`.
        
        Returns:
            None.
        """

        self.metrics.append(
            MetricResult(
                name=name,
                value=value,
                unit=unit,
                description=description,
            )
        )

    def add_warning(self, warning: str) -> None:
        """Add a warning generated during analysis.
        
        Args:
            warning: Value for `warning`.
        
        Returns:
            None.
        """

        self.warnings.append(warning)

    def add_message(self, message: str) -> None:
        """Add an informational message.
        
        Args:
            message: Message text.
        
        Returns:
            None.
        """

        self.messages.append(message)

    def add_evidence(
        self,
        statement: str,
        strength: EvidenceStrength,
        supporting_metrics: list[str] | None = None,
    ) -> None:
        """Add evidence that may support a later diagnostic hypothesis.
        
        Args:
            statement: Value for `statement`.
            strength: Value for `strength`.
            supporting_metrics: Value for `supporting_metrics`.
        
        Returns:
            None.
        """

        self.evidence.append(
            Evidence(
                statement=statement,
                strength=strength,
                supporting_metrics=supporting_metrics or [],
            )
        )

    def to_dict(self) -> dict[str, Any]:
        """Convert the complete result into a dictionary.
        
        This will later allow results to be:
        - sent through the API
        - saved as JSON
        - displayed in the frontend
        - included in reports
        
        Returns:
            Dictionary containing the result values.
        """

        return asdict(self)


@dataclass
class RequirementCheck:
    """
    Result of comparing one calculated metric against
    an engineering requirement.

    Requirement checking is intentionally kept separate
    from the analysis tool itself.
    """

    metric_name: str
    measured_value: float | int | None
    unit: str | None

    requirement_description: str

    status: QualificationStatus

    limit_value: float | int | None = None
    operator: str | None = None

    message: str | None = None


@dataclass
class QualifiedAnalysisResult:
    """
    Combines the raw analysis result with engineering
    requirement evaluations.

    The analysis tool calculates the metric.

    The requirements engine decides whether the metric passes.
    """

    analysis: AnalysisResult
    requirement_checks: list[RequirementCheck] = field(default_factory=list)

    def overall_status(self) -> QualificationStatus:
        """Determine the overall qualification status for this analysis.
        
        Returns:
            QualificationStatus returned by the function.
        """

        if not self.requirement_checks:
            return QualificationStatus.NOT_EVALUATED

        statuses = [check.status for check in self.requirement_checks]

        if QualificationStatus.FAIL in statuses:
            return QualificationStatus.FAIL

        evaluated = [
            status
            for status in statuses
            if status != QualificationStatus.NOT_EVALUATED
        ]

        if evaluated and all(
            status == QualificationStatus.PASS for status in evaluated
        ):
            return QualificationStatus.PASS

        return QualificationStatus.NOT_EVALUATED

    def to_dict(self) -> dict[str, Any]:
        """Convert the qualified result into a serializable dictionary.
        
        Returns:
            Dictionary containing the result values.
        """

        return asdict(self)
